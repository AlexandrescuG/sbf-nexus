/**
 * logo-roles.js — какая роль у знака на текущей секции.
 *
 * Раньше этот модуль ещё и возил знак по экрану: он был один, position: fixed,
 * и переезжал в центр вьюпорта. Это работало, пока страница двигалась целыми
 * экранами — тогда «центр вьюпорта» совпадал с центром спроектированной
 * композиции. После перехода на обычную прокрутку центр экрана попадает на
 * произвольный абзац, и знак начал ложиться на текст. Подкруткой отступов
 * это не лечится: конфликт в самой модели.
 *
 * Теперь знаков два вида, и ни один не плавает над содержимым:
 *   · постоянный маленький в шапке (#sbf-logo) — с кольцом текущей роли;
 *   · крупные внутри секций (.sect-mark) — лежат в потоке и едут со своей
 *     секцией, поэтому перекрыть ничего не могут физически.
 *
 * Здесь остаётся только справочник ролей: им пользуется logo-aura.js,
 * чтобы знать, какую долю кольца рисовать.
 */
(function () {
  'use strict';

  var ROLES = {
    'act-map':        'source',   /* нити новостей сходятся в знак */
    'act-grow':       'spread',   /* из знака выходят четыре продукта */
    'act-platform-1': 'entry',    /* знак — вход на платформу */
    'act-platform-2': 'issue',    /* опрос превращается в доступ */
    'act-service-1':  'hold-1',   /* треть работы на нашей стороне */
    'act-service-2':  'hold-2',
    'act-service-3':  'hold-3',
    'act-contact':    'sun',
  };

  function roleOf(id) { return ROLES[id] || null; }

  window.SBF_LOGO_ROLES = { roleOf: roleOf, ROLES: ROLES };
})();
