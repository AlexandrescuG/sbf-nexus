/* viewport.js — высота окна, устойчивая к адресной строке телефона.

   На iOS при прокрутке адресная строка Safari сворачивается и
   разворачивается, и innerHeight меняется десятки раз за один жест.
   Chrome на Android так не делает — держит высоту постоянной. Отсюда и
   жалоба «на iPhone 12 лагает, а на слабом Android нет»: разница не в
   мощности, а в движке.

   Замерено щупом tools/scene-urlbar.py: десять «свернулась/развернулась»
   стоили десяти полных пересчётов карты актов (getBoundingClientRect по
   каждой секции) и трёх перепечек подложек глобуса. Холст при этом НЕ
   пересоздавался — вопреки первой догадке: слой закреплён по layout
   viewport, а он на iOS постоянен. Дорого было другое — камера. Она
   считает взгляд по середине окна, и середина уезжала вместе со строкой:
   доля пройденного акта менялась без единого движения пальца, а за ней
   менялся тон мира и перепекалась подложка.

   Поэтому на сенсорных экранах высота только РАСТЁТ: берём самый высокий
   виденный кадр (строка свёрнута) и держимся его. Когда строка вернётся,
   лишняя полоса уйдёт под нижний край — .scene-layer её обрезает.

   Модуль отдельный, потому что этим числом пользуются двое — камера и
   сцена, — и оно должно быть у них ОДНО. Ровно из-за двух копий одного
   числа в первой версии сайта логотип наезжал на текст. */

const coarse = window.matchMedia &&
               window.matchMedia('(pointer: coarse)').matches;

let held = 0, heldFor = 0;

/* Высота, по которой считают и камера, и сцена. */
export function vh() {
  const now = window.innerHeight;
  if (!coarse) return now;
  /* Поворот экрана — настоящая смена размера: держаться старой высоты
     после него значит рисовать в вертикальный холст на горизонтальном
     экране. Ширина здесь и есть признак поворота. */
  if (window.innerWidth !== heldFor) { held = 0; heldFor = window.innerWidth; }
  if (now > held) held = now;
  return held;
}
