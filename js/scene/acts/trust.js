/* trust.js — акт «что известно и насколько этому можно верить».

   Кольцо знака делится на три дуги — по одной на уровень источника:
   котировки, СМИ, соцсети. Дуги гаснут в том же порядке и теми же
   тремя ступенями яркости, что и полосы слева от текста в колонке
   (.act-tiers в css/scene.css). Это одно утверждение, сказанное дважды:
   глазом — по кольцу, буквами — в списке.

   Почему не проценты и не доли: у уровней нет веса. «Из котировок» не
   «в три раза вернее», чем «из СМИ», — это просто разные источники с
   разной проверяемостью. Поэтому дуги равные, а различает их только
   яркость, которая ничего не измеряет и ни на что не делится.

   Красного здесь нет намеренно. Непроверенное — не ложное: рынок на
   него реагирует, и мы его показываем именно поэтому. Цвет тревоги
   сказал бы «не читайте это», а мы говорим «читайте, но знайте цену».
*/

import { t } from '../labels.js';

/* Яркость по уровням — те же три ступени, что в CSS. Разъехались бы,
   если бы каждая сторона держала свои числа. */
const TONE = [0.85, 0.55, 0.28];
const GAP = 0.08;              /* просвет между дугами, в долях трети */

export const trust = {
  id: 'trust',
  role: 'process',
  note: 'три уровня доверия: котировки, СМИ, соцсети',

  lit: 0,

  render(ctx, view, cam, mark, labels) {
    const w = cam.w;
    if (w < 0.02) return;
    const g = mark.geometry(view);
    /* Сколько уровней уже показано. Считаем по числу блоков в ленте, а
       не по трём всегда: если бриф принёс два уровня, третья дуга
       обещала бы источник, которого на экране нет. */
    const meta = window.SBF_FEED_META;
    const n = Math.min(3, (((meta && meta.grow) || {}).context || []).length);
    if (!n) return;

    const target = Math.min(1, Math.max(0, cam.t / 0.5));
    this.lit += (target - this.lit) * Math.min(1, view.dt * 3);

    const r = g.r * 1.16;
    const step = Math.PI * 2 / n;

    ctx.save();
    ctx.lineCap = 'butt';
    ctx.lineWidth = Math.max(3, g.r * 0.05);
    for (let i = 0; i < n; i++) {
      const on = Math.max(0, Math.min(1, this.lit * n - i));
      if (on <= 0.01) continue;
      const a0 = -Math.PI / 2 + step * (i + GAP / 2);
      const a1 = -Math.PI / 2 + step * (i + 1 - GAP / 2);
      ctx.globalAlpha = w * on * TONE[i];
      ctx.strokeStyle = '#C9A227';
      ctx.beginPath();
      ctx.arc(g.cx, g.cy, r, a0, a1);
      ctx.stroke();
    }
    ctx.restore();

    /* Подписи у своей дуги — иначе три одинаковые дуги разной яркости
       читаются как украшение. Берутся из того же словаря, что и
       заголовки блоков в колонке. */
    /* Подписи — только на широком экране. На телефоне знак стоит прямо
       над колонкой, и подпись нижней дуги ложилась на заголовок: «СМИ»
       оказывалось посреди строки «Что известно — и насколько». Имя у дуг
       там и так есть — три блока под кольцом названы теми же словами и
       идут в том же порядке. */
    if (labels && !view.mobile) {
      /* Короткие имена, не заголовки блоков: «из соцсетей, не проверено»
         у кольца тянулось на треть экрана и залезало внутрь знака.
         Полная формулировка стоит в колонке, где её и читают. */
      const keys = ['know.r_quotes', 'know.r_media', 'know.r_social'];
      const fall = ['котировки', 'СМИ', 'соцсети'];
      for (let i = 0; i < n; i++) {
        const on = Math.max(0, Math.min(1, this.lit * n - i));
        if (on <= 0.05) continue;
        const a = -Math.PI / 2 + step * (i + 0.5);
        labels.put('trust-' + i, t(keys[i], fall[i]),
                   g.cx + Math.cos(a) * (r + 30),
                   g.cy + Math.sin(a) * (r + 30),
                   { align: 'center', alpha: w * on * Math.max(0.5, TONE[i]) });
      }
    }
  },

  enter() { this.lit = 0; },
  leave() {},
};
